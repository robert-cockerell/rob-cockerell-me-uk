-- Fittings get their own ID (approved by Rob, 14 November 2026; replaces
-- schema notes choice S-3).
--
-- The CRP script fits the same battery twice in one held minute (S4.03 then
-- S4.05 at 08:05; S12.05 then S12.08 at 16:20). With battery and Fitted from
-- as the key, the second fitting was refused, which DEC-06 rules out (no
-- duplicate-fitting check). Now each fitting has a sequential ID; the latest
-- is by Fitted from, then Recorded at, then ID.

alter table public.fittings drop constraint fittings_pkey;

-- Existing rows are numbered as the column is added.
alter table public.fittings add column fitting_id bigint generated by default as identity;
alter table public.fittings add primary key (fitting_id);

create index fittings_battery_idx on public.fittings (battery_asset_tag, fitted_from desc, fitting_id desc);

comment on table public.fittings is
	'D2 Fitting. Insert only (BR-07). bike_asset_tag null = battery removed (DEC-20). Latest = fitted_from, then recorded_at, then fitting_id.';

-- The reset names the columns now, so the new ID is assigned, not loaded.
create or replace function public.reset_planner_data(payload jsonb)
returns void
language plpgsql
set search_path = ''
as $$
begin
	truncate public.fittings, public.entries, public.batteries, public.bikes, public.battery_types;

	insert into public.battery_types
	select * from jsonb_populate_recordset(null::public.battery_types, coalesce(payload -> 'battery_types', '[]'));

	insert into public.bikes
	select * from jsonb_populate_recordset(null::public.bikes, coalesce(payload -> 'bikes', '[]'));

	insert into public.batteries
	select * from jsonb_populate_recordset(null::public.batteries, coalesce(payload -> 'batteries', '[]'));

	insert into public.fittings (battery_asset_tag, fitted_from, bike_asset_tag, recorded_by, recorded_at)
	select battery_asset_tag, fitted_from, bike_asset_tag, recorded_by, recorded_at
	from jsonb_populate_recordset(null::public.fittings, coalesce(payload -> 'fittings', '[]'));

	insert into public.entries overriding system value
	select * from jsonb_populate_recordset(null::public.entries, coalesce(payload -> 'entries', '[]'));

	-- New entries carry on after the highest fixture ID.
	perform setval(
		pg_get_serial_sequence('public.entries', 'entry_id'),
		coalesce((select max(entry_id) from public.entries), 0) + 1,
		false
	);

	insert into public.forecast_periods
	select * from jsonb_populate_recordset(null::public.forecast_periods, coalesce(payload -> 'forecast_periods', '[]'))
	on conflict (region, period_start) do update set
		forecast_intensity = excluded.forecast_intensity,
		index_band = excluded.index_band,
		retrieved_at = excluded.retrieved_at;
end;
$$;

revoke all on function public.reset_planner_data(jsonb) from public, anon, authenticated;
grant execute on function public.reset_planner_data(jsonb) to service_role;

revoke all on sequence public.fittings_fitting_id_seq from public, anon, authenticated;
grant usage, select on sequence public.fittings_fitting_id_seq to service_role;
